export const MAX_SHARE_BYTES = MAX_R2_UPLOAD_BYTES;

/** 讨论组自动归档：24 小时无新消息即归档（有人再发言自动恢复活跃） */
export const THREAD_AUTO_ARCHIVE_MS = 24 * 60 * 60 * 1000;

/** 讨论组名称最大长度（字符） */
export const THREAD_NAME_MAX = 80;

/** 从消息发起讨论时，name/摘要最多截取多少字符 */
export const THREAD_STARTER_SNIPPET_MAX = 100;

/**
 * 新建社区时自动发到「公告」频道并置顶的开箱指南（Markdown）。
 * 目的：新社区不要一进去就是空白 —— 创建者与首批成员都能立刻看到「这个社区怎么用」。
 * 内容只描述产品通用能力，不假设社区主题；创建者可随时编辑或删除。
 */
export const NEW_COMMUNITY_GUIDE = `**这里是社区的公告频道** —— 默认全员只读，仅所有者或被单独授权的角色/成员可发布。

## 社区怎么用

1. **拉人进来**：频道列表顶部的社区名旁「⋯」菜单 →「邀请码」，把码发给对方，对方在左栏「＋」→「加入」里输入即可；也可以「邀请用户」按用户名或邮箱直接邀请，对方会在收件箱收到通知。
2. **建频道**：社区名旁「⋯」→「新建频道」，三种类型——
   - **文字**：全员自由发言
   - **公告**：默认只读，适合发通知（就是本频道）
   - **话题**：先开话题、再进话题里聊，适合「一个问题一条线」
3. **发消息**：支持 Markdown 与 \`@成员\`、\`@everyone\` 提醒；输入框下方可加附件（图片内联预览）与表情，粘贴 / 拖拽文件也能直接加入待发送列表。
4. **分享 DSH 会话**：输入框下方第一个按钮可以把本机一条 DSH 会话打包发到频道里，别人点开卡片就能**一键克隆到自己的 DSH**。把调好的 Agent 工作流直接交给同事，是这个工具最有用的玩法。
5. **权限**：社区名旁「⋯」→「角色管理」可建自定义角色、勾选权限位；频道还能对 \`@everyone\` / 角色 / 成员单独设置允许与拒绝。

`;
